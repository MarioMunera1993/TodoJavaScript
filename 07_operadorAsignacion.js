//Operadores de Asignación

// Asignación simple
let x = 10;
console.log("El valor de x es: " + x);

// Asignación con suma
x += 5;
console.log("El valor de x después de la asignación con suma es: " + x);

// Asignación con resta
x -= 3;
console.log("El valor de x después de la asignación con resta es: " + x);

// Asignación con multiplicación
x *= 2;
console.log("El valor de x después de la asignación con multiplicación es: " + x);

// Asignación con división
x /= 4;
console.log("El valor de x después de la asignación con división es: " + x);

// Asignación con módulo
x %= 3;
console.log("El valor de x después de la asignación con módulo es: " + x);

// Asignación con potenciación
x **= 2;
console.log("El valor de x después de la asignación con potenciación es: " + x);

