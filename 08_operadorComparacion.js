//Operadores de comparación

let a = 5;
let b = 10;
let c = '5';

// Igualdad
console.log(a == b);

// Igualdad estricta
console.log(a === c); // es false porque el tipo de dato es diferente

// Desigualdad
console.log(a != b);

// Mayor que
console.log(a > b);

// Menor que
console.log(a < b);

// Mayor o igual que
console.log(a >= b);

// Menor o igual que
console.log(a <= b);
